/**
 * # stills — the director of the large-format image surfaces (plan v20x A4)
 *
 * **Responsibility.** Shows the game's large approved artwork — ending illustrations, story
 * stills, menu backdrops — behind the procedural scene art, on the renderer's image surface
 * (`@shmup/render-pixi` `stills`). The cutscene director's sibling, and built on its two
 * shipped halves: the page-image factory of the loader (v20x P0-1 — bytes over the
 * `file://`-safe XHR, `createImageBitmap` with the `Image` fallback) and the guarded bitmap
 * close (the VRAM law). Like the cutscene module it imports neither Pixi nor render-pixi at
 * runtime — the surface and the release ride in as options, so the director is tested without
 * a renderer.
 *
 * - **The manifest** ({@link STILL_SURFACES}) names the shipped files (served from
 *   {@link STILLS_URL_DIR} by the build's `shmupStills` plugin, generated by the deterministic
 *   encode kit `scripts/v20x/stills-encode.mjs`) and keys them to what selects them: the
 *   campaign **ending id** (the five approved `moment/ending-*` paintings are the design
 *   sources of the five ending epilogues — ARTLEDGER §3.5; story-page stills join the table
 *   when their approved art arrives).
 * - **The watch** ({@link StillsDirector.update}, once per drawn frame next to the cutscene's):
 *   reads the flow's top scene and run ending — fields the sim already publishes — and on a
 *   change shows or releases the still. A frame inside an ending whose id the table names
 *   loads it once (cold path); a frame outside releases it (closed, zero held bytes — the
 *   residency law). The watch is a string compare when nothing changed: no allocation, no
 *   fetch, no texture.
 * - **The switches** ({@link resolveStillsSetting}): the host option, the baked
 *   `__SHMUP_NO_STILLS__` define (the `SHMUP_NO_STILLS=1` build), the page global
 *   `SHMUP_NO_STILLS` and `?nostills=1` turn the feature off (no surface, no texture, no
 *   watch); the browser spec's `?still=<id>` forces a surface for the pixel probe; the shipped
 *   default is **on** — a static image decoded once at a scene edge carries none of the media
 *   pacing the video default-off was measured into (the M7 lesson, R7-VID).
 * - **Failure is invisible.** A missing file, a refused decode or a dead surface leaves the
 *   procedural scene exactly as it drew before this feature; an orphaned late decode (its
 *   scene already gone, or a newer one in flight) is closed at once through the injected
 *   release and never shown.
 *
 * **Implements.**
 * - shmup_tech.md §2.5 — the TV memory budget (a resident still is what the estimator's
 *   `stills` line charges, `memory/index.ts`)
 * - shmup_feat.md §18 — draw order (the surface lives in the layer stack's bands, never a layer)
 *
 * **Public API.** {@link STILL_SURFACES}, {@link STILLS_URL_DIR}, {@link STILL_DEFAULT_ON},
 * {@link StillsSurface}, {@link stillForEnding}, {@link createStillsDirector},
 * {@link StillsDirector}, {@link StillsDirectorOptions}, {@link StillsSurfaceLike},
 * {@link StillsImageLike}, {@link StillsFlow}, {@link resolveStillsSetting},
 * {@link stillsSettingFromWindow}, {@link stillProbeFromSearch}, {@link StillsWindowLike}.
 *
 * @module
 */
import { defineModule } from '@shmup/core';

