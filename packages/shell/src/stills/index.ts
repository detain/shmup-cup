/**
 * The still a campaign ending shows (the manifest's `ending` key, scanned cold at a scene
 * edge — five rows, no table to rot).
 *
 * @param endingId - `run.ending.id` (an unknown or null id has no still).
 * @returns The surface row, or null.
 */
export function stillForEnding(endingId: string | null): StillsSurface | null {
  if (endingId === null) return null;
  for (const row of STILL_SURFACES) if (row.ending === endingId) return row;
  return null;
}

/** The `?still=` / `?nostills=` search shapes (the browser spec's hooks and the kill switch). */
const STILL_PROBE_PATTERN = /[?&]still=([^&]*)/;
const NO_STILLS_PATTERN = /[?&]nostills=1/;

/**
 * The `?still=<id>` probe surface (the e2e spec's hook), or `null`.
 *
 * @param search - `location.search`.
 * @returns The surface id to force while an ending scene runs, when named and known.
 */
export function stillProbeFromSearch(search: string): string | null {
  const match = STILL_PROBE_PATTERN.exec(search);
  if (match === null) return null;
  const id = match[1] ?? '';
  for (const row of STILL_SURFACES) if (row.id === id) return id;
  return null;
}

/** The fields {@link resolveStillsSetting} reads (all optional so a bare fake window passes). */
export interface StillsWindowLike {
  /** The page location (`search` only). */
  readonly location?: { readonly search?: string } | undefined;
  /** The page global `SHMUP_NO_STILLS` (the harness / app kill switch). */
  readonly SHMUP_NO_STILLS?: unknown;
}

/** Inputs of {@link resolveStillsSetting}. */
export interface StillsSettingHost {
  /** The host's explicit decision (`ShellOptions.stills`) — wins over everything. */
  readonly override?: boolean | undefined;
  /** The page global `SHMUP_NO_STILLS` (`1` / `true` / `'1'` turn the feature off). */
  readonly noStillsGlobal?: unknown;
  /** The page search (`?nostills=1`, `?still=<id>`). */
  readonly search?: string;
}

/**
 * Whether the stills feature is on, in precedence order (the video resolver's shape, with no
 * stored choice — a still is not a player setting, and no default-off pacing risk — R7-VID's
 * measured media risk does not exist for a single static decode): the host option, then the
 * baked define / page global (folded into `override` / `noStillsGlobal` by the caller), then
 * `?nostills=1`, then the forced probe (the spec's tool overrides the switches the way
 * `?video=` does), then {@link STILL_DEFAULT_ON}.
 *
 * @param host - The switches.
 * @returns Whether the feature is on.
 */
export function resolveStillsSetting(host: StillsSettingHost): boolean {
  if (host.override !== undefined) return host.override;
  const flag = host.noStillsGlobal;
  if (flag === 1 || flag === true || flag === '1') return false;
  const search = host.search ?? '';
  if (NO_STILLS_PATTERN.test(search)) return false;
  if (stillProbeFromSearch(search) !== null) return true;
  return STILL_DEFAULT_ON;
}

/**
 * {@link resolveStillsSetting} reading search and global off a window.
 *
 * @param win - The page window (or a fake shaped like {@link StillsWindowLike}).
 * @param override - The host's explicit decision (`ShellOptions.stills`).
 * @returns Whether the feature is on.
 */
export function stillsSettingFromWindow(win: StillsWindowLike, override?: boolean): boolean {
  return resolveStillsSetting({
    override,
    noStillsGlobal: win.SHMUP_NO_STILLS,
    search: win.location?.search ?? '',
  });
}

/**
 * The image the surface shows and the release closes — the shape both `ImageBitmap` and
 * `HTMLImageElement` provide (the page-image factory's output, an `AtlasPageImage`).
 */
export interface StillsImageLike {
  /** The decoded width in pixels. */
  readonly width: number;
  /** The decoded height in pixels. */
  readonly height: number;
}

/** What the director drives — satisfied by `@shmup/render-pixi`'s `ImageSurface`. */
export interface StillsSurfaceLike {
  /**
   * Shows a decoded image (the surface takes ownership of it; {@link StillsDirectorOptions.closeImage}
   * says how to release one it must never show).
   *
   * @param image - The decoded still.
   */
  show(image: StillsImageLike): void;
  /** Releases the resident still (the VRAM law: closed and destroyed, zero held). */
  hide(): void;
  /**
   * Moves the quad between the draw bands.
   *
   * @param band - The band the current still belongs to.
   */
  setBand(band: 'world' | 'screen'): void;
  /** Whether a still is resident now (the estimator's flag). */
  readonly shown: boolean;
}

/** The flow state the director reads (the structural subset of core's `SceneFlow`). */
export interface StillsFlow {
  /** The scene stack (top = the drawn scene). */
  readonly stack: { readonly top?: { readonly id: string } | null };
  /** The campaign run (its selected ending names the still). */
  readonly run: { readonly ending: { readonly id: string } | null };
}

/** Options of {@link createStillsDirector}. */
export interface StillsDirectorOptions {
  /** The scene flow to watch (the game's). */
  readonly flow: StillsFlow;
  /** Whether the feature is on (the boot's {@link resolveStillsSetting}). */
  readonly enabled: boolean;
  /** The renderer's image surface, or `null` (built without the option — the watch is inert). */
  readonly surface: StillsSurfaceLike | null;
  /** Loads and decodes one shipped file (the boot's page-image factory over the still url). */
  readonly loadImage: (url: string) => Promise<StillsImageLike>;
  /** Releases an image the surface will never show (the boot passes render-pixi `closePageImage`). */
  readonly closeImage: (image: StillsImageLike) => void;
  /** The `?still=<id>` probe: forces that surface while an ending scene runs. */
  readonly probeStill?: string | null;
  /** Where the files are served (default {@link STILLS_URL_DIR}). */
  readonly base?: string;
  /**
   * Mirrors what shows (the boot writes the canvas `data-shmup-still` attribute from it — the
   * browser spec's join point).
   *
   * @param still - The surface id now shown, or `null` for none.
   */
  readonly onStillChange?: (still: string | null) => void;
}

/** What {@link createStillsDirector} returns. */
export interface StillsDirector {
  /**
   * One watch pass, from the frame loop (never from `render()` on this side): finds the still
   * the flow's ending names (or the probe's), and on a change starts its load or releases the
   * resident one. A frame that changed nothing compares two strings and allocates nothing.
   */
  update(): void;
  /** Releases the resident still and forgets the scene (the boot's teardown). */
  destroy(): void;
  /** Whether a still is resident right now (delegates to the surface; false without one). */
  readonly showing: boolean;
}

/**
 * Builds the director (see the module docblock). It owns the in-flight rule: at most one load
 * is trusted at a time (a generation counter), so a slow decode of a still the player already
 * left cannot show or leak — its image is closed by {@link StillsDirectorOptions.closeImage}
 * the moment it settles.
 *
 * @param options - Flow, surface, loader, release and switches.
 * @returns The director.
 *
 * @example
 * ```ts
 * const stills = createStillsDirector({ flow, enabled, surface, loadImage, closeImage });
 * // … once per drawn frame:
 * stills.update();
 * ```
 */
export function createStillsDirector(options: StillsDirectorOptions): StillsDirector {
  const { flow, enabled, surface, loadImage, closeImage } = options;
  const base = options.base ?? STILLS_URL_DIR;
  const probe = options.probeStill ?? null;
  const onStillChange = options.onStillChange;
  /** The surface id the watch believes is (or is loading as) shown, `null` for none. */
  let shownId: string | null = null;
  /** The generation of the last-started load (a newer load orphans the older one's image). */
  let generation = 0;

  /**
   * Moves to a new still (or to none): the cold-path edge of a scene transition. Releases the
   * resident picture only when the watch settles on none; a swap keeps the old one up until
   * the new image arrives, so no scene edge flashes the bare procedural backdrop away.
   *
   * @param next - The surface id to show, or `null`.
   */
  const move = (next: string | null): void => {
    if (next === shownId) return;
    shownId = next;
    if (surface === null) return;
    if (next === null) {
      generation++;
      surface.hide();
      onStillChange?.(null);
      return;
    }
    let row: StillsSurface | null = null;
    for (const candidate of STILL_SURFACES) {
      if (candidate.id === next) {
        row = candidate;
        break;
      }
    }
    if (row === null) {
      shownId = null;
      surface.hide();
      onStillChange?.(null);
      return;
    }
    const wanted = next;
    const seq = ++generation;
    surface.setBand(row.band);
    loadImage(`${base}/${row.file}`).then(
      (image) => {
        // The orphan rule: an image whose watch has moved on (newer load, scene left, destroy)
        // is closed unseen; only the newest generation may show.
        if (seq !== generation || shownId !== wanted || surface === null) {
          closeImage(image);
          return;
        }
        surface.show(image);
        onStillChange?.(wanted);
      },
      (_error) => {
        // Failure is invisible: the procedural scene stands, and a resident older still keeps
        // drawing until the watch's own release (no blanking on a fetch miss).
        if (seq !== generation || shownId !== wanted) return;
        shownId = null;
        onStillChange?.(null);
      },
    );
  };

  return {
    update(): void {
      if (!enabled || surface === null) return;
      const top = flow.stack.top;
      const stillId =
        top !== undefined && top !== null && top.id === 'ending'
          ? probe !== null
            ? probe
            : stillIdOfEnding(flow.run.ending)
          : null;
      move(stillId);
    },
    destroy(): void {
      generation++;
      shownId = null;
      surface?.hide();
      onStillChange?.(null);
    },
    get showing(): boolean {
      return surface !== null && surface.shown;
    },
  };
}

/**
 * The probe-or-ending id a frame wants (kept out of `update` so the frame path stays a
 * compare; cold either way — five rows).
 *
 * @param ending - The run's selected campaign ending (null outside one).
 * @returns The surface id, or null.
 */
function stillIdOfEnding(ending: { readonly id: string } | null): string | null {
  const row = stillForEnding(ending === null ? null : ending.id);
  return row === null ? null : row.id;
}
